import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import {fileURLToPath} from "node:url";
import {loadDevelopmentProfiles,resolveDevelopmentProfile,selectDevelopmentBinding,selectDevelopmentBindingFromCatalog} from "../src/development-profiles.mjs";

const {catalog,catalog_digest}=loadDevelopmentProfiles();
assert.match(catalog_digest,/^[a-f0-9]{64}$/u);
const packageRoot=path.resolve(path.dirname(fileURLToPath(import.meta.url)),"..");
assert(fs.readFileSync(path.join(packageRoot,"README.md"),"utf8").includes(`계약 SHA-256은 \`${catalog_digest}\``));
assert.equal(catalog.default_opt_in_profile,"balanced");
assert.equal(resolveDevelopmentProfile().profile.id,"balanced");
assert.equal(selectDevelopmentBinding({role:"orchestrator"}).binding_id,"sol");
assert.equal(selectDevelopmentBinding({role:"bounded_worker",boundedScope:true,risk:"medium"}).binding_id,"terra");
const unboundedWorker=selectDevelopmentBinding({role:"bounded_worker",boundedScope:false,risk:"low"});
assert.equal(unboundedWorker.binding_id,"sol");
assert.equal(unboundedWorker.fallback_reason,"bounded engineering guard");
assert.equal(unboundedWorker.total_cost_reduction_proven,false);
assert.equal(selectDevelopmentBinding({role:"bounded_worker",boundedScope:true,risk:"high"}).binding_id,"sol");
assert.equal(selectDevelopmentBinding({role:"tester",boundedScope:true,risk:"medium"}).binding_id,"terra");
assert.equal(selectDevelopmentBinding({role:"tester",boundedScope:false,risk:"low"}).binding_id,"sol");
assert.equal(selectDevelopmentBinding({profileId:"economy",role:"mechanical_worker",boundedScope:true,exactValidator:true,risk:"low"}).binding_id,"luna");
assert.equal(selectDevelopmentBinding({profileId:"economy",role:"mechanical_worker",boundedScope:true,exactValidator:false,risk:"low"}).binding_id,"terra");
assert.equal(selectDevelopmentBinding({profileId:"economy",role:"mechanical_worker",boundedScope:true,exactValidator:true,risk:"medium"}).binding_id,"terra");
assert.equal(selectDevelopmentBinding({profileId:"economy",role:"mechanical_worker",boundedScope:false,exactValidator:false,risk:"high"}).binding_id,"sol");
const independentReview={producerSessionId:"writer-session",reviewerSessionId:"review-session",producerExecutionId:"writer-execution",reviewerExecutionId:"review-execution"};
assert.equal(selectDevelopmentBinding({role:"adversarial_reviewer",producerBinding:"terra",...independentReview}).binding_id,"sol");
assert.equal(selectDevelopmentBinding({role:"adversarial_reviewer",producerBinding:"sol",...independentReview}).binding_id,"terra");
const controlReview=selectDevelopmentBinding({profileId:"control",role:"adversarial_reviewer",producerBinding:"sol",...independentReview});
assert.equal(controlReview.binding_id,"sol");
assert.equal(controlReview.total_cost_reduction_proven,false);
assert.throws(()=>selectDevelopmentBinding({role:"adversarial_reviewer",producerBinding:"terra"}),/distinct session and execution/);
assert.throws(()=>selectDevelopmentBinding({role:"adversarial_reviewer",producerBinding:"terra",...independentReview,reviewerSessionId:"writer-session"}),/distinct session and execution/);
assert.throws(()=>selectDevelopmentBinding({role:"adversarial_reviewer",producerBinding:"terra",...independentReview,reviewerExecutionId:"writer-execution"}),/distinct session and execution/);
const changedGuards=structuredClone(catalog);
changedGuards.guards.bounded_worker.maximum_risk="low";
changedGuards.guards.bounded_worker.fallback_binding="terra";
assert.equal(selectDevelopmentBindingFromCatalog(changedGuards,{role:"bounded_worker",boundedScope:true,risk:"medium"}).binding_id,"terra");
changedGuards.guards.review.prefer_different_binding_from_producer=false;
assert.equal(selectDevelopmentBindingFromCatalog(changedGuards,{role:"adversarial_reviewer",producerBinding:"terra",...independentReview}).binding_id,"terra");
assert.throws(()=>resolveDevelopmentProfile("future-model-name"),/unknown development composition profile/);
console.log("development profiles: PASS (3 role profiles, guarded fallback, independent review selection, model-binding separation)");
