#!/usr/bin/env node
/**
 * Deterministic .agents/context/*.json -> .users/context/*.md mirror.
 * Runs natively on Windows and Linux; no WSL/MSYS path conversion is used.
 */
const fs = require("fs");
const path = require("path");

function eventFilePath(data) {
  return (data && (
    (data.tool_response && (data.tool_response.filePath || data.tool_response.file_path)) ||
    (data.tool_input && (data.tool_input.file_path || data.tool_input.path))
  )) || "";
}

function render(node, depth) {
  const heading = "#".repeat(Math.min(depth, 6));
  let output = "";
  if (Array.isArray(node)) {
    for (const value of node) {
      output += value && typeof value === "object"
        ? render(value, depth) + "\n"
        : "- " + String(value) + "\n";
    }
    return output;
  }
  if (node && typeof node === "object") {
    for (const [key, value] of Object.entries(node)) {
      if (key.startsWith("$")) continue;
      output += value && typeof value === "object"
        ? "\n" + heading + " " + key + "\n\n" + render(value, depth + 1)
        : "- **" + key + "**: " + String(value) + "\n";
    }
    return output;
  }
  return String(node) + "\n";
}

function syncContextMirror(data, cwd = process.cwd()) {
  const raw = eventFilePath(data);
  if (!raw) return { updated: false, reason: "no-path" };

  const filePath = path.resolve(cwd, raw).replace(/\\/g, "/");
  const match = filePath.match(/^(.*)\/\.agents\/context\/([^/]+)\.json$/);
  if (!match) return { updated: false, reason: "not-context-json" };

  const projectRoot = match[1];
  const name = match[2];
  const mirrorPath = path.join(projectRoot, ".users", "context", name + ".md");
  if (!fs.existsSync(filePath)) return { updated: false, reason: "source-missing" };
  if (!fs.existsSync(path.dirname(mirrorPath))) return { updated: false, reason: "mirror-dir-missing" };

  let source;
  try {
    source = JSON.parse(fs.readFileSync(filePath, "utf8"));
  } catch {
    return { updated: false, reason: "invalid-json" };
  }

  const header =
    "<!-- AUTO-GENERATED from .agents/context/" + name + ".json — DO NOT EDIT BY HAND.\n" +
    "     SoT = json. Edit the JSON; this file is regenerated by the hook. -->\n\n" +
    "# " + name + " (mirror)\n\n" +
    "> Machine SoT: .agents/context/" + name + ".json; this Markdown file is generated.\n";
  fs.writeFileSync(mirrorPath, header + render(source, 2), "utf8");
  return { updated: true, name, mirrorPath };
}

function main() {
  let data;
  try {
    data = JSON.parse(fs.readFileSync(0, "utf8"));
  } catch {
    return 0;
  }
  try {
    const result = syncContextMirror(data);
    if (result.updated) {
      console.log(JSON.stringify({
        systemMessage: "[mirror] .users/context/" + result.name + ".md synchronized",
        suppressOutput: true,
      }));
    }
  } catch (error) {
    console.log(JSON.stringify({ systemMessage: "[mirror] synchronization failed: " + error.message }));
  }
  return 0;
}

if (require.main === module) process.exitCode = main();
module.exports = { eventFilePath, main, render, syncContextMirror };